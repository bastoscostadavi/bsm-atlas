import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const directory=path.dirname(fileURLToPath(import.meta.url));
const context={window:{}};
for(const file of ['data.js','search.js']) vm.runInNewContext(fs.readFileSync(path.join(directory,file),'utf8'),context);
const models=context.window.ATLAS_DATA.modelData.models;
const search=context.window.AtlasSearch;
const paperIds=results=>Array.from(results,p=>p.id);
const su5=search.findPapers(models,{gauge:'SU(5)'});
assert.deepEqual(paperIds(su5),['P11','P18','P22']);
assert.equal(new Set(su5.flatMap(p=>p.matches.map(m=>m.modelId))).size,5);
assert.equal(su5.reduce((total,p)=>total+p.matches.length,0),7);
assert.deepEqual(paperIds(search.findPapers(models,{gauge:'SU(5)',role:'category:review'})),['P11','P22']);
assert.deepEqual(paperIds(search.findPapers(models,{gauge:'SU(5)',role:'category:formulation'})),['P18']);
assert.deepEqual(paperIds(search.findPapers(models,{gauge:'SU(5)',role:'category:analysis'})),['P18']);
assert.deepEqual(paperIds(search.findPapers(models,{gauge:'SU(5)',role:'model_formulation_and_fermion_mass_analysis'})),['P18']);
assert.deepEqual(paperIds(search.findPapers(models,{gauge:'SU(5)',text:'adjoint'})),['P18']);
const synthetic=[{i:'a',n:'A',g:[['SU(3)C × U(1)Y','','','','SU(3)C × U(1)Y']],z:[['P1','1','Paper','model_formulation','scope','summary','provisional']]},
 {i:'b',n:'B',g:[['SU(5)','','','','']],z:[['P1','1','Paper','structural_review','scope','summary','provisional']]}];
assert.equal(search.findPapers(synthetic,{gauge:'SU(3)',mode:'exact'}).length,0);
assert.equal(search.findPapers(synthetic,{gauge:'  SU(3)C   × U(1)Y  ',mode:'exact'}).length,1);
assert.equal(search.findPapers(synthetic,{gauge:'SU(3)C',mode:'factor'}).length,1);
assert.equal(search.findPapers(synthetic,{gauge:'SU(3)c',mode:'factor'}).length,0);
assert.equal(search.findPapers(synthetic,{gauge:'SU(5)',mode:'factor'}).length,0);
assert.equal(search.findPapers(synthetic).length,1);
assert.equal(search.findPapers(synthetic)[0].matches.length,2);
assert.equal(search.categoriesFor('messenger_construction_review').includes('formulation'),false);
console.log('Gauge/role search validated: SU(5) results, paper deduplication, combined filters, exact labels, factor coverage and case conventions.');
