import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const website=new URL('../website/',import.meta.url);
const context={URLSearchParams,location:{hash:'#problems'},history:{replaceState(_s,_t,h){context.location.hash=h;}}};
context.window=context;
for(const file of ['problem-data.js','problem-explorer.js','field-matrix.js','field-catalogue.js'])vm.runInNewContext(fs.readFileSync(new URL(file,website),'utf8'),context);
const data=JSON.parse(fs.readFileSync(new URL('field-catalogue.json',website)));
const annotations=context.ATLAS_PROBLEMS,explorer=context.ProblemExplorer.create(data,annotations);
assert.equal(Object.values(annotations.links).reduce((n,x)=>n+Object.keys(x).length,0),1473);
assert.equal(Object.values(annotations.links).flatMap(x=>Object.values(x)).reduce((n,x)=>n+x.length,0),4265);
assert.equal(annotations.problems.length,13);
assert(!annotations.categories.some(c=>c.id==='established_theory_dynamics'));
assert.equal((explorer.overview('established_theory_dynamics').match(/class="problem-card"/g)||[]).length,13);
const overview=explorer.overview();
assert.equal((overview.match(/class="problem-card"/g)||[]).length,13);
assert(overview.includes('Neutrino masses')&&overview.includes('Dark matter'));
for(const removed of ['Experimental','Search problems','problem-categories','problem-stats','16 problem definitions'])assert(!overview.includes(removed));
assert(overview.includes('About Problems'));
assert(overview.includes('Problems adds a literature-based layer to the atlas'));
assert(!overview.includes('Problems layer'));
assert(overview.includes('13 problems'));
// Problem lists retain the mathematical catalogue order, including across algebras.
const linkedOrder=Array.from(explorer.problem('dark_matter','',2000).matchAll(/<h3><a href="#entry\/([^?]+)\?panel=problems/g),m=>decodeURIComponent(m[1]));
assert.deepEqual(linkedOrder,data.entries.filter(e=>annotations.links[e.id]?.dark_matter).map(e=>e.id));
assert.equal(explorer.count('mssm-matter'),13);
const unassessed=data.entries.find(e=>!explorer.assessed(e.id));
const zero=data.entries.find(e=>explorer.assessed(e.id)&&!explorer.count(e.id));
assert(explorer.entry(unassessed.id).includes('It is unassessed'));
assert(explorer.entry(zero.id).includes('No “addresses” associations'));
assert(explorer.problem('qcd_mass_gap').includes('Problem not found'));
assert(!explorer.entry('mssm-matter').includes('>Confinement</span>'));
assert(explorer.problem('dark_matter','nuMSM').includes('46 supporting papers'));
assert(!explorer.problem('dark_matter','nuMSM').includes('<h3><a href="#entry/mssm-matter'));
assert(explorer.entry('numsm').includes('Evidence review needed'));
// Source text is escaped even inside quotations and rationales.
const unsafe=context.ProblemExplorer.create(data,{...annotations,links:{numsm:{dark_matter:[{paperId:data.papers[0].id,rationale:'<script>x</script>',needsReview:true,evidence:[{quote:'<img onerror="x">',locator:'<bad>'}]}]}}});
assert(unsafe.entry('numsm').includes('&lt;script&gt;'));
assert(!unsafe.entry('numsm').includes('<img'));
const nodes=new Map(),document={getElementById(id){if(!nodes.has(id))nodes.set(id,{});return nodes.get(id);}};
const app=context.FieldCatalogue.create(data,document);
context.location.hash='#problems?about=layer';app.route();app.render();
assert.equal(app.state.problemLayer,true);
assert.equal(nodes.get('problems-layer').open,true);
assert.equal(nodes.get('page-title').textContent,'Problems');
context.location.hash='#atlas';app.route();app.render();
const paragraphs=Array.from(nodes.get('view-content').innerHTML.matchAll(/<p>(.*?)<\/p>/g),m=>m[1]);
assert(paragraphs[2].includes('href="#problems?about=layer"'));
for(const [view,title] of [['sources','Papers'],['notation','Notation']]){
 context.location.hash='#'+view;app.route();app.render();
 assert.equal(nodes.get('page-title').textContent,title);
}
context.location.hash='#problems/dark_matter?search=nuMSM';app.route();app.render();
assert.equal(app.state.view,'problems');assert.equal(app.state.problem,'dark_matter');
assert(nodes.get('view-content').innerHTML.includes('46 supporting papers'));
context.location.hash='#entry/numsm?panel=problems';app.route();app.render();
assert.equal(app.state.panel,'problems');
assert(nodes.get('model-entries').innerHTML.includes('Problem associations'));
app.url();assert(context.location.hash.includes('panel=problems'));
context.location.hash='#entry/numsm';app.route();app.render();
assert.equal(app.state.panel,'references');
assert(nodes.get('model-entries').innerHTML.includes('Papers in chronological order'));
console.log('Problem categories, source evidence, coverage states and entry routes passed.');
